"""OTLP decoding: Sibyl's dependency-free protobuf reader agrees with the official
opentelemetry-proto encoder (fixtures generated by it), OTLP/JSON decodes to the same model,
and hostile bodies fail closed."""

from __future__ import annotations

import base64
import json
from pathlib import Path
from typing import Any

import pytest
from sibyl_control.ingest.otlp import (
    AnyBytes,
    OtlpDecodeError,
    TooManyItems,
    decode_logs,
    decode_traces,
    encode_logs_response,
    encode_traces_response,
)
from sibyl_control.ingest.otlp.wire import encode_varint

FIXTURES = Path(__file__).parent / "fixtures" / "otlp"


def _any(value: Any) -> Any:
    """Our AnyValue representation -> the generator's tagged JSON form."""
    if isinstance(value, AnyBytes):
        return {"bytes": value.data.hex()}
    if isinstance(value, float):
        return {"double": value}
    if isinstance(value, list):
        return {"array": [_any(v) for v in value]}
    if isinstance(value, dict):
        return {"kvlist": {k: _any(v) for k, v in value.items()}}
    return value


def _attrs(attrs: dict[str, Any]) -> dict[str, Any]:
    return {k: _any(v) for k, v in attrs.items()}


def _walk_traces(batch: Any) -> list[dict[str, Any]]:
    return [
        {
            "resource": _attrs(rs.resource),
            "schema_url": rs.schema_url,
            "scopes": [
                {
                    "name": ss.scope.name,
                    "version": ss.scope.version,
                    "attributes": _attrs(ss.scope.attributes),
                    "schema_url": ss.schema_url,
                    "spans": [
                        {
                            "trace_id": s.trace_id.hex(),
                            "span_id": s.span_id.hex(),
                            "parent_span_id": s.parent_span_id.hex(),
                            "name": s.name,
                            "kind": s.kind,
                            "start_ns": s.start_ns,
                            "end_ns": s.end_ns,
                            "attributes": _attrs(s.attributes),
                            "status_code": s.status_code,
                            "status_message": s.status_message,
                            "events": [
                                {
                                    "name": e.name,
                                    "time_ns": e.time_ns,
                                    "attributes": _attrs(e.attributes),
                                }
                                for e in s.events
                            ],
                        }
                        for s in ss.spans
                    ],
                }
                for ss in rs.scopes
            ],
        }
        for rs in batch.resources
    ]


def _walk_logs(batch: Any) -> list[dict[str, Any]]:
    return [
        {
            "resource": _attrs(rl.resource),
            "scopes": [
                {
                    "name": sl.scope.name,
                    "version": sl.scope.version,
                    "records": [
                        {
                            "time_ns": r.time_ns,
                            "observed_ns": r.observed_ns,
                            "severity_number": r.severity_number,
                            "severity_text": r.severity_text,
                            "body": _any(r.body),
                            "attributes": _attrs(r.attributes),
                            "event_name": r.event_name,
                            "trace_id": r.trace_id.hex(),
                            "span_id": r.span_id.hex(),
                        }
                        for r in sl.records
                    ],
                }
                for sl in rl.scopes
            ],
        }
        for rl in batch.resources
    ]


def test_protobuf_traces_match_the_reference_encoder() -> None:
    batch = decode_traces(
        (FIXTURES / "traces.pb").read_bytes(), content_type="application/x-protobuf"
    )
    expected = json.loads((FIXTURES / "traces.expected.json").read_text("utf-8"))
    assert _walk_traces(batch) == expected
    assert batch.span_count == 3


def test_protobuf_logs_match_the_reference_encoder() -> None:
    batch = decode_logs((FIXTURES / "logs.pb").read_bytes(), content_type="application/x-protobuf")
    expected = json.loads((FIXTURES / "logs.expected.json").read_text("utf-8"))
    assert _walk_logs(batch) == expected
    assert batch.record_count == 2


def test_protobuf_json_mapping_decodes_to_the_same_model() -> None:
    """protobuf's canonical JSON (base64 ids, int64 as strings) is accepted too."""
    pb = decode_traces((FIXTURES / "traces.pb").read_bytes(), content_type="application/x-protobuf")
    js = decode_traces(
        (FIXTURES / "traces.otlp.json").read_bytes(), content_type="application/json"
    )
    assert _walk_traces(js) == _walk_traces(pb)


def _hexify(doc: Any) -> Any:
    """Rewrite protobuf-JSON base64 ids into the OTLP/JSON hex spelling."""
    if isinstance(doc, dict):
        out = {}
        for key, value in doc.items():
            if key in ("traceId", "spanId", "parentSpanId") and value:
                out[key] = base64.b64decode(value).hex()
            else:
                out[key] = _hexify(value)
        return out
    if isinstance(doc, list):
        return [_hexify(v) for v in doc]
    return doc


def test_otlp_json_with_hex_ids_decodes_to_the_same_model() -> None:
    pb = decode_traces((FIXTURES / "traces.pb").read_bytes(), content_type="application/x-protobuf")
    doc = _hexify(json.loads((FIXTURES / "traces.otlp.json").read_text("utf-8")))
    js = decode_traces(json.dumps(doc).encode(), content_type="application/json; charset=utf-8")
    assert _walk_traces(js) == _walk_traces(pb)


def test_partial_success_responses_are_byte_identical_to_the_reference() -> None:
    assert (
        encode_traces_response(3, '[{"reason":"missing_required"}]', protobuf=True)
        == (FIXTURES / "traces_response_partial.pb").read_bytes()
    )
    assert (
        encode_logs_response(1, "x", protobuf=True)
        == (FIXTURES / "logs_response_partial.pb").read_bytes()
    )
    assert encode_traces_response(0, "", protobuf=True) == b""
    assert json.loads(encode_traces_response(2, "m", protobuf=False)) == {
        "partialSuccess": {"rejectedSpans": "2", "errorMessage": "m"}
    }
    assert json.loads(encode_traces_response(0, "", protobuf=False)) == {}


def test_empty_request_is_a_valid_heartbeat() -> None:
    assert decode_traces(b"", content_type="application/x-protobuf").span_count == 0
    assert decode_traces(b"{}", content_type="application/json").span_count == 0
    assert decode_logs(b"", content_type="application/x-protobuf").record_count == 0


@pytest.mark.parametrize(
    "body",
    [
        b"\x0a",  # length-delimited field with no length
        b"\x0a\x05abc",  # length past the end
        b"\x0a" + encode_varint(1 << 40),  # absurd length
        b"\x0b",  # wire type 3 (start group) is refused
        b"\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\x01",  # 11-byte varint
        b"\x09\x00",  # truncated fixed64
    ],
)
def test_malformed_protobuf_is_refused(body: bytes) -> None:
    with pytest.raises(OtlpDecodeError):
        decode_traces(body, content_type="application/x-protobuf")


def test_deeply_nested_anyvalue_is_refused() -> None:
    value: Any = {"stringValue": "leaf"}
    for _ in range(40):
        value = {"arrayValue": {"values": [value]}}
    doc = {
        "resourceSpans": [
            {
                "scopeSpans": [
                    {
                        "spans": [
                            {
                                "traceId": "0" * 31 + "1",
                                "spanId": "0" * 15 + "1",
                                "attributes": [{"key": "deep", "value": value}],
                            }
                        ]
                    }
                ]
            }
        ]
    }
    with pytest.raises(OtlpDecodeError, match="nest"):
        decode_traces(json.dumps(doc).encode(), content_type="application/json")


def test_duplicate_json_keys_are_refused() -> None:
    with pytest.raises(OtlpDecodeError):
        decode_traces(
            b'{"resourceSpans": [], "resourceSpans": []}', content_type="application/json"
        )


def test_span_count_limit_is_enforced_while_decoding() -> None:
    spans = [{"traceId": "0" * 31 + "1", "spanId": f"{i:016x}"} for i in range(5)]
    doc = {"resourceSpans": [{"scopeSpans": [{"spans": spans}]}]}
    with pytest.raises(TooManyItems):
        decode_traces(json.dumps(doc).encode(), content_type="application/json", max_items=4)
    assert (
        decode_traces(
            json.dumps(doc).encode(), content_type="application/json", max_items=5
        ).span_count
        == 5
    )


def test_attribute_limits_truncate_and_warn() -> None:
    attrs = [{"key": f"k{i}", "value": {"stringValue": "v"}} for i in range(300)]
    attrs.append({"key": "long", "value": {"stringValue": "x" * (70 * 1024)}})
    doc = {
        "resourceSpans": [
            {
                "scopeSpans": [
                    {
                        "spans": [
                            {
                                "traceId": "0" * 31 + "1",
                                "spanId": "0" * 15 + "1",
                                "attributes": attrs[-1:] + attrs[:-1],
                            }
                        ]
                    }
                ]
            }
        ]
    }
    batch = decode_traces(json.dumps(doc).encode(), content_type="application/json")
    span = batch.resources[0].scopes[0].spans[0]
    assert len(span.attributes) == 256
    assert len(span.attributes["long"]) == 64 * 1024
    assert any("attributes" in w for w in batch.warnings)
    assert any("64 KiB" in w for w in batch.warnings)


def test_unknown_content_type_is_refused() -> None:
    with pytest.raises(OtlpDecodeError, match="content type"):
        decode_traces(b"", content_type="text/plain")


def test_invalid_utf8_string_is_refused() -> None:
    # Span{name: b"\xff"} inside ScopeSpans inside ResourceSpans.
    span = b"\x2a\x01\xff"
    scope_spans = b"\x12" + encode_varint(len(span)) + span
    resource_spans = b"\x12" + encode_varint(len(scope_spans)) + scope_spans
    body = b"\x0a" + encode_varint(len(resource_spans)) + resource_spans
    with pytest.raises(OtlpDecodeError, match="UTF-8"):
        decode_traces(body, content_type="application/x-protobuf")
