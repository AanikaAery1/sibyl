"""External monitor agents (D53): request bodies for monitors, their keys and webhooks, and
the findings a monitor submits.

A monitor is any outside agent (Claude, an OpenAI or Gemini agent, an Agent SDK app, an
MCP-capable assistant or a plain script) that watches the fleet through a monitor-bound key
(``monitor:read`` + ``findings:write``). Findings are **advisory exactly like Sentinel's**: they
can open a watch-only ``external_finding`` alert and attach a recommendation to a held action;
they never allow, block, approve, fail over or change policy. Bodies are closed (unknown fields
are a 422) because they come from outside the trust boundary.
"""

from __future__ import annotations

import json
import re
from datetime import datetime
from typing import Any, Final, Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from sibyl_schemas._enums_monitor import (
    FIXED_SUBJECT_OF_KIND,
    SUBSCRIBABLE_EVENTS,
    ExternalFindingKind,
    ExternalSubjectKind,
    HeldActionAdvice,
    MonitorKind,
    WebhookEventType,
)
from sibyl_schemas._enums_sentinel import SentinelFeedback, SentinelSeverity

MAX_WATCHED_GROUPS: Final = 64
MAX_BODY_BYTES: Final = 32_768
DEFAULT_RATE_LIMIT_PER_MIN: Final = 60
MAX_RATE_LIMIT_PER_MIN: Final = 600
NAME_PATTERN: Final = r"^[^\x00-\x1f\x7f]{1,128}$"
PROVIDER_PATTERN: Final = r"^[a-z0-9][a-z0-9._-]{0,63}$"
MODEL_PATTERN: Final = r"^[A-Za-z0-9][A-Za-z0-9._:/-]{0,127}$"
_CONTROL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


class _Body(BaseModel):
    model_config = ConfigDict(extra="forbid")


def _check_groups(all_groups: bool | None, group_ids: list[UUID] | None) -> None:
    if all_groups and group_ids:
        raise ValueError("group_ids must be empty when all_groups is true")
    if all_groups is False and not group_ids:
        raise ValueError("a monitor that does not watch all groups needs group_ids")
    if group_ids is not None and len(set(group_ids)) != len(group_ids):
        raise ValueError("group_ids must be unique")


class MonitorCreate(_Body):
    """``POST /monitors``: registers the monitor and, unless ``issue_key`` is false, issues its
    first key (the secret is in the 201 response once)."""

    name: str = Field(pattern=NAME_PATTERN)
    kind: MonitorKind
    description: str | None = Field(default=None, max_length=2000)
    owner_user_id: UUID | None = None
    all_groups: bool = True
    group_ids: list[UUID] = Field(default_factory=list, max_length=MAX_WATCHED_GROUPS)
    rate_limit_per_min: int = Field(
        default=DEFAULT_RATE_LIMIT_PER_MIN, ge=1, le=MAX_RATE_LIMIT_PER_MIN
    )
    issue_key: bool = True
    key_env: Literal["live", "test"] | None = None
    key_expires_at: datetime | None = None
    reason: str | None = Field(default=None, min_length=10, max_length=2000)

    @model_validator(mode="after")
    def _shape(self) -> MonitorCreate:
        _check_groups(self.all_groups, self.group_ids)
        return self


class MonitorPatch(_Body):
    """``PATCH /monitors/{id}``: pause or resume, rename, change watched groups or the rate."""

    name: str | None = Field(default=None, pattern=NAME_PATTERN)
    description: str | None = Field(default=None, max_length=2000)
    state: Literal["active", "paused"] | None = None
    owner_user_id: UUID | None = None
    all_groups: bool | None = None
    group_ids: list[UUID] | None = Field(default=None, max_length=MAX_WATCHED_GROUPS)
    rate_limit_per_min: int | None = Field(default=None, ge=1, le=MAX_RATE_LIMIT_PER_MIN)
    reason: str | None = Field(default=None, min_length=10, max_length=2000)

    @model_validator(mode="after")
    def _shape(self) -> MonitorPatch:
        changes = self.model_dump(exclude_unset=True, exclude={"reason"})
        if not changes:
            raise ValueError("nothing to change")
        if (self.all_groups is None) != (self.group_ids is None):
            raise ValueError("all_groups and group_ids are changed together")
        _check_groups(self.all_groups, self.group_ids)
        return self


class MonitorRevoke(_Body):
    reason: str = Field(min_length=10, max_length=2000)


class MonitorKeyCreate(_Body):
    """``POST /monitors/{id}/keys``: another key for the monitor (``monitor:read`` +
    ``findings:write``)."""

    name: str | None = Field(default=None, min_length=1, max_length=80)
    env: Literal["live", "test"] | None = None
    expires_at: datetime | None = None
    reason: str | None = Field(default=None, min_length=10, max_length=2000)


class WebhookCreate(_Body):
    """``POST /monitors/{id}/webhooks``: an https endpoint on the egress allowlist; the signing
    secret is generated by Sibyl and returned once."""

    url: str = Field(min_length=8, max_length=2048)
    event_types: list[WebhookEventType] = Field(min_length=1, max_length=len(SUBSCRIBABLE_EVENTS))
    reason: str | None = Field(default=None, min_length=10, max_length=2000)

    @field_validator("event_types")
    @classmethod
    def _events(cls, value: list[WebhookEventType]) -> list[WebhookEventType]:
        if len(set(value)) != len(value):
            raise ValueError("event_types must be unique")
        if WebhookEventType.PING in value:
            raise ValueError("ping is the test delivery and cannot be subscribed")
        return value

    @field_validator("url")
    @classmethod
    def _url(cls, value: str) -> str:
        if _CONTROL.search(value) or any(c.isspace() for c in value):
            raise ValueError("url must not contain whitespace or control characters")
        return value


class FindingSubmit(_Body):
    """``POST /findings`` (monitor key): the Sentinel finding shape plus the monitor's own model
    metadata. Advisory only."""

    kind: ExternalFindingKind
    subject_kind: ExternalSubjectKind
    subject_id: UUID | None = None
    severity: SentinelSeverity
    summary: str = Field(min_length=1, max_length=2000)
    body: dict[str, Any] = Field(default_factory=dict)
    recommendation: str | None = Field(default=None, max_length=2000)
    advice: HeldActionAdvice | None = None
    confidence: Literal["low", "medium", "high"] | None = None
    provider: str | None = Field(default=None, pattern=PROVIDER_PATTERN)
    model: str | None = Field(default=None, pattern=MODEL_PATTERN)
    raise_alert: bool | None = None

    @field_validator("summary", "recommendation")
    @classmethod
    def _text(cls, value: str | None) -> str | None:
        if value is not None and _CONTROL.search(value):
            raise ValueError("control characters are not allowed")
        return value

    @field_validator("body")
    @classmethod
    def _body_size(cls, value: dict[str, Any]) -> dict[str, Any]:
        try:
            raw = json.dumps(value, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
        except (TypeError, ValueError):
            raise ValueError("body must be plain JSON") from None
        if len(raw.encode("utf-8")) > MAX_BODY_BYTES:
            raise ValueError(f"body exceeds {MAX_BODY_BYTES} bytes")
        return value

    @model_validator(mode="after")
    def _shape(self) -> FindingSubmit:
        fixed = FIXED_SUBJECT_OF_KIND.get(self.kind)
        if fixed is not None and self.subject_kind is not fixed:
            raise ValueError(f"kind {self.kind.value} is about a {fixed.value}")
        if self.subject_kind is ExternalSubjectKind.FLEET:
            if self.subject_id is not None:
                raise ValueError("a fleet finding has no subject_id")
        elif self.subject_id is None:
            raise ValueError(f"subject_id is required for subject_kind {self.subject_kind.value}")
        if self.advice is not None and self.kind is not ExternalFindingKind.HELD_ACTION_REVIEW:
            raise ValueError("advice is only for held_action_review findings")
        if self.raise_alert and self.severity is SentinelSeverity.INFO:
            raise ValueError("an info finding never raises an alert")
        return self

    def wants_alert(self) -> bool:
        """Critical findings alert unless told not to; warnings only when asked."""
        if self.severity is SentinelSeverity.CRITICAL:
            return self.raise_alert is not False
        if self.severity is SentinelSeverity.WARNING:
            return bool(self.raise_alert)
        return False


class FindingFeedbackBody(_Body):
    feedback: SentinelFeedback


