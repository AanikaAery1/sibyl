from pathlib import Path
from types import ModuleType

import pytest


def _dist(lic: ModuleType, name: str, licence: str) -> object:
    return lic.Dist(name=name, version="1.0", licence=licence)


@pytest.mark.parametrize(
    ("expression", "status"),
    [
        ("MIT", "allow"),
        ("MIT-0", "allow"),
        ("BSD-3-Clause", "allow"),
        ("Apache-2.0", "allow"),
        ("PSF-2.0", "allow"),
        ("ISC", "allow"),
        ("Apache-2.0 OR BSD-3-Clause", "allow"),
        ("(Apache-2.0 OR BSD-2-Clause)", "allow"),
        ("GPL-2.0-or-later OR MIT", "allow"),
        ("MIT AND GPL-3.0-only", "deny"),
        ("GPL-3.0-only", "deny"),
        ("GPL-2.0", "deny"),
        ("AGPL-3.0-or-later", "deny"),
        ("SSPL-1.0", "deny"),
        ("BUSL-1.1", "deny"),
        ("Elastic-2.0", "deny"),
        ("RSALv2", "deny"),
        ("LGPL-3.0-or-later", "flag"),
        ("LGPL-2.1-only", "flag"),
        ("MPL-2.0", "flag"),
        ("", "unknown"),
        ("UNKNOWN", "unknown"),
        ("Some Custom Licence", "unknown"),
    ],
)
def test_classify_expression(licences: ModuleType, expression: str, status: str) -> None:
    assert licences.classify(expression).status == status


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("BSD 2-Clause License", "BSD-2-Clause"),
        ("Apache 2.0", "Apache-2.0"),
        ("Apache Software License", "Apache-2.0"),
        ("MIT License", "MIT"),
        ("GNU General Public License v3 (GPLv3)", "GPL-3.0"),
        ("GNU Lesser General Public License v3 (LGPLv3)", "LGPL-3.0"),
        ("GNU Affero General Public License v3", "AGPL-3.0"),
        ("Mozilla Public License 2.0 (MPL 2.0)", "MPL-2.0"),
    ],
)
def test_normalise_free_text(licences: ModuleType, raw: str, expected: str) -> None:
    assert licences.normalise(raw) == expected


def test_licence_of_prefers_expression_then_field_then_classifier(licences: ModuleType) -> None:
    meta = licences.licence_from_fields
    assert meta("MIT", "whatever", []) == "MIT"
    assert meta(None, "BSD-3-Clause", []) == "BSD-3-Clause"
    assert meta(None, "", ["License :: OSI Approved :: MIT License"]) == "MIT"
    long_text = "Copyright (c) 2020\n" + "Permission is hereby granted " * 20
    assert meta(None, long_text, ["License :: OSI Approved :: BSD License"]) == "BSD-3-Clause"
    assert meta(None, "", []) == "UNKNOWN"


