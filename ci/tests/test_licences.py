def test_npm_dev_only_copyleft_is_listed_not_gating(licences: ModuleType, tmp_path: Path) -> None:
    dists, runtime = licences.npm_inventory(_lockfile(tmp_path, SAMPLE))
    report = licences.evaluate(dists, runtime=runtime)
    assert report.exit_code == 0
    classes = {e.dist.name: e.klass for e in report.entries}
    assert classes["axe-core"] == classes["lightningcss-linux-x64-gnu"] == "build/ci-only"
    assert [e.dist.name for e in report.flags] == ["@img/sharp-libvips-linux-x64"], "LGPL"


def test_npm_waiver_never_matches_a_pypi_package(licences: ModuleType) -> None:
    pypi = licences.Dist(name="axe-core", version="1", licence="GPL-3.0")
    report = licences.evaluate([pypi], runtime={"axe-core"}, waivers={"npm:axe-core": "B15: x"})
    assert report.exit_code == 1
    assert report.unused_waivers == ("npm:axe-core",)


def test_b15_waives_axe_core_as_dev_only(licences: ModuleType) -> None:
    waivers = licences.load_waivers(licences.DEFAULT_WAIVERS)
    for key in ("npm:@axe-core/playwright", "npm:axe-core"):
        assert waivers[key].startswith("B15: "), key
        assert "dev/test-only" in waivers[key]


def test_console_lockfile_passes_the_gate_with_the_b15_waiver(licences: ModuleType) -> None:
    dists, runtime = licences.npm_inventory(CONSOLE_LOCK)
    waivers = licences.load_waivers(licences.DEFAULT_WAIVERS)
    report = licences.evaluate(dists, runtime=runtime, waivers=waivers)
    assert report.exit_code == 0, licences.render_markdown(report)
    entries = {e.dist.name: e for e in report.entries}
    for name in ("@axe-core/playwright", "axe-core"):
        assert entries[name].klass == "build/ci-only", f"{name} must never be bundled (B15)"
        assert entries[name].waiver is not None
    assert "npm:next" in runtime
    assert "npm:@axe-core/playwright" not in runtime
    assert not report.unused_waivers


def test_cli_inventories_python_and_console_together(licences: ModuleType, tmp_path: Path) -> None:
    inventory = tmp_path / "inv.json"
    inventory.write_text('[{"name": "goodlib", "version": "1", "licence": "MIT"}]')
    lock = _lockfile(tmp_path, SAMPLE)
    out_md, out_json = tmp_path / "o.md", tmp_path / "o.json"
    code = licences.main(
        ["--inventory", str(inventory), "--npm-lock", str(lock), "--waivers", str(tmp_path / "w"),
         "--output", str(out_md), "--json", str(out_json)]
    )  # fmt: skip
    assert code == 0
    md = out_md.read_text(encoding="utf-8")
    assert "| goodlib | 1 | MIT | bundled | allow |" in md
    assert "| npm:next | 16.4.0 | MIT | bundled | allow |" in md
    assert "| npm:axe-core | 4.10.0 | MPL-2.0 | build/ci-only | flag |" in md
    rows = {(r["ecosystem"], r["name"]): r for r in json.loads(out_json.read_text())}
    assert rows[("npm", "next")]["class"] == "bundled"
    assert rows[("pypi", "goodlib")]["class"] == "bundled"


