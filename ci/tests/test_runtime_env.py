"""Compose hands every process the configuration its code actually reads (INT-2, item 3).

The process code is the source of truth: ``Settings`` + ``PROCESS_SECRETS`` (control),
``AuthSettings`` (api), ``GatewayConfig`` (gateway, B12) and the sim CLI. Each test builds the
environment a container would see from compose alone (``environment`` + the committed env-file
example + the granted file secrets, generated by init-env.sh) and runs the process's own startup
check against it. A required secret that compose does not grant, or a misspelt variable such as
``SIBYL_MASTER_KEK``, fails here before it fails at ``docker compose up``.
"""

