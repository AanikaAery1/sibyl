def test_console_is_a_trusted_proxy_of_the_api_inside_the_edge_subnet(
    compose: dict[str, Any], generated: Path
) -> None:
    env, _ = _container_env(compose, "api", generated)
    trusted = parse_trusted_proxies(env["SIBYL_TRUSTED_PROXIES"])
    edge = compose["networks"]["edge"]["ipam"]["config"][0]["subnet"]
    subnet = ipaddress.ip_network(_interpolate(edge))
    for service in ("caddy", "console"):
        pinned = _interpolate(compose["services"][service]["networks"]["edge"]["ipv4_address"])
        address = ipaddress.ip_address(pinned)
        assert address in subnet, service
        assert any(address in net for net in trusted), f"api must trust {service}"
    assert len(trusted) == 2, "only Caddy and the console"


