def _container_env(
    compose: dict[str, Any],
    service: str,
    env_dir: Path,
    fills: dict[str, str] | None = None,
    variables: dict[str, str] | None = None,
) -> tuple[dict[str, str], dict[str, Path]]:
    """(environment, /run/secrets|/etc mounts -> host files) as the container would see them.

    ``fills`` stands in for secrets minted after first boot (empty in a fresh env dir);
    ``variables`` are compose interpolation variables (.env), defaults when absent.
    """
    svc = compose["services"][service]
    env: dict[str, str] = {}
    for entry in svc.get("env_file", []):
        env.update(_env_example(entry["path"] if isinstance(entry, dict) else entry))
    for key, value in (svc.get("environment") or {}).items():
        env[key] = _interpolate("" if value is None else str(value), variables)
    mounts: dict[str, Path] = {}
    for entry in svc.get("secrets", []):
        source = entry if isinstance(entry, str) else entry["source"]
        target = entry if isinstance(entry, str) else entry.get("target", source)
        host = env_dir / "secrets" / source
        mounts[f"/run/secrets/{target}"] = host
        if target.startswith(("SIBYL_", "DEX_")):  # the entrypoint shim exports these
            env[target] = (fills or {}).get(source) or host.read_text(encoding="utf-8")
    for entry in svc.get("configs", []):
        source, target = entry["source"], entry["target"]
        template = compose["configs"][source]["file"]
        if template.startswith("${SIBYL_ENV_DIR:-./env}/"):
            mounts[target] = env_dir / template.removeprefix("${SIBYL_ENV_DIR:-./env}/")
        else:
            mounts[target] = (COMPOSE_DIR / _interpolate(template, variables)).resolve()
    # Paths inside the container resolve to the host files that back them.
    for key, value in list(env.items()):
        if value in mounts:
            env[key] = str(mounts[value])
    return env, mounts


@pytest.fixture
def clean_environ(monkeypatch: pytest.MonkeyPatch) -> Iterator[pytest.MonkeyPatch]:
    for key in list(os.environ):
        if key.startswith("SIBYL_"):
            monkeypatch.delenv(key)
    yield monkeypatch


