def _interpolate(value: str, variables: dict[str, str] | None = None) -> str:
    """Compose interpolation with ``variables`` as the .env: ``${V:-default}``, ``${V:+alt}``."""
    given = variables or {}

    def one(match: re.Match[str]) -> str:
        name, op, operand = match.group(1), match.group(2) or "", match.group(3) or ""
        value = given.get(name, "")
        if op.endswith("+"):
            return operand if value else ""
        return value or operand

    return INTERPOLATION.sub(one, value)


def _env_example(path_template: str) -> dict[str, str]:
    path = COMPOSE_DIR / (path_template.replace("${SIBYL_ENV_DIR:-./env}", "env") + ".example")
    out: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            key, _, value = line.partition("=")
            out[key] = value
    return out


