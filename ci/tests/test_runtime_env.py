@pytest.mark.parametrize("process", ["api", "worker"])
def test_saga_gates_default_off(
    compose: dict[str, Any], generated: Path, clean_environ: pytest.MonkeyPatch, process: str
) -> None:
    """D36: the predicted band stays "0.90" and the canary failback ramp stays off."""
    env, _ = _container_env(compose, process, generated)
    for key, value in env.items():
        clean_environ.setenv(key, value)
    settings = Settings()
    assert settings.predicted_automation_band == "0.90"
    assert settings.failback_ramp is False
    variables = {"SIBYL_PREDICTED_AUTOMATION_BAND": "0.60", "SIBYL_FAILBACK_RAMP": "true"}
    env, _ = _container_env(compose, process, generated, variables=variables)
    for key, value in env.items():
        clean_environ.setenv(key, value)
    flipped = Settings()
    assert (flipped.predicted_automation_band, flipped.failback_ramp) == ("0.60", True)


