@pytest.mark.parametrize("process", CONTROL)
def test_control_process_starts_with_exactly_what_compose_grants(
    compose: dict[str, Any], generated: Path, clean_environ: pytest.MonkeyPatch, process: str
) -> None:
    env, _ = _container_env(compose, process, generated)
    for key, value in env.items():
        clean_environ.setenv(key, value)
    settings = Settings()
    settings.require_secrets(process)  # raises naming every missing secret
    assert settings.dsn().startswith("postgresql://sibyl_")
    assert settings.port_for(process) == {"api": 8000, "ingest": 8001, "worker": 8002}[process]


@pytest.mark.parametrize("process", CONTROL)
def test_required_secret_missing_from_compose_is_caught(
    compose: dict[str, Any], generated: Path, clean_environ: pytest.MonkeyPatch, process: str
) -> None:
    """The check above has teeth: drop any one required secret and startup refuses."""
    env, _ = _container_env(compose, process, generated)
    for name in PROCESS_SECRETS[process]:
        for key, value in env.items():
            clean_environ.setenv(key, value)
        clean_environ.delenv(name)
        with pytest.raises(RuntimeError, match=name):
            Settings().require_secrets(process)


def test_api_gets_the_auth_secrets(
    compose: dict[str, Any], generated: Path, clean_environ: pytest.MonkeyPatch
) -> None:
    env, _ = _container_env(compose, "api", generated)
    for key, value in env.items():
        clean_environ.setenv(key, value)
    auth = AuthSettings()
    assert len(auth.secret()) >= 32, "SIBYL_SESSION_SECRET (>= 32 chars)"
    assert auth.oidc_client_secret is not None and auth.oidc_client_secret.get_secret_value()
    assert auth.cookie_secure, "the console origin is https (Caddy)"


def _known_names() -> set[str]:
    names = {f"SIBYL_{f.upper()}" for f in Settings.model_fields}
    names |= {f"SIBYL_{f.upper()}" for f in AuthSettings.model_fields}
    for path in (
        REPO_ROOT / "services/gateway/src/sibyl_gateway/config.py",
        REPO_ROOT / "services/control/src/sibyl_control/migrate/config.py",
        REPO_ROOT / "services/control/src/sibyl_control/core/blob/s3.py",
        REPO_ROOT / "sibyl-sim/src/sibyl_sim/doubles/cli.py",
        *READ_ELSEWHERE.values(),
    ):
        names |= set(re.findall(r'"(SIBYL_[A-Z0-9_]+)"', path.read_text(encoding="utf-8")))
    return names


def test_read_elsewhere_names_are_really_read() -> None:
    for name, path in READ_ELSEWHERE.items():
        assert f'"{name}"' in path.read_text(encoding="utf-8"), f"{name} not read in {path.name}"


@pytest.mark.parametrize(
    "service", ["bootstrap", "migrate", *CONTROL, "gateway", "console", "sibyl-sim"]
)
def test_every_variable_compose_sets_is_read_by_the_process(
    compose: dict[str, Any], generated: Path, service: str
) -> None:
    """No dead or misspelt names (the old SIBYL_MASTER_KEK vs Settings.kek class of bug)."""
    env, _ = _container_env(compose, service, generated)
    known = _known_names() | set(DEPLOY_ONLY)
    if service == "sibyl-sim":
        known |= set(AWAITING_READER)
    if service == "bootstrap":
        known |= {
            n for n in env if n.startswith("SIBYL_ROLE_PASSWORD_")
        }  # migrate/config.py builds these names from the role list
    if service == "console":
        known |= set(
            re.findall(
                r"process\.env\.(SIBYL_[A-Z0-9_]+)",
                "\n".join(
                    p.read_text(encoding="utf-8") for p in (REPO_ROOT / "console/lib").rglob("*.ts")
                ),
            )
        )
    unknown = sorted(n for n in env if n.startswith("SIBYL_") and n not in known)
    assert not unknown, f"{service}: nothing reads {unknown}"


