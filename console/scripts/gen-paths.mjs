#!/usr/bin/env node
/**
 * Emits lib/api/paths.gen.ts: the contract's path templates as a runtime list, so the live BFF
 * forwards only real contract routes (never `..` tricks or non-contract API paths). Run by
 * `npm run gen:api` after openapi-typescript. Path keys are the 2-space-indented `/…:` lines
 * under `paths:` in the frozen OpenAPI document.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "..", "openapi", "sibyl-api.v1.yaml");
const out = path.join(here, "..", "lib", "api", "paths.gen.ts");

const text = await readFile(src, "utf8");
const lines = text.split("\n");
const start = lines.findIndex((l) => l === "paths:");
if (start < 0) throw new Error("no top-level paths: in the OpenAPI document");
const paths = [];
for (const line of lines.slice(start + 1)) {
  if (/^\S/.test(line)) break; // next top-level key
  const m = /^  (\/[^\s:]*):\s*$/.exec(line);
  if (m) paths.push(m[1]);
}
if (paths.length === 0) throw new Error("no paths found");
const body = `// Generated by scripts/gen-paths.mjs from openapi/sibyl-api.v1.yaml. Do not edit.\nexport const CONTRACT_PATHS: readonly string[] = ${JSON.stringify(paths.sort(), null, 2)};\n`;
await writeFile(out, body);
console.log(`paths.gen.ts: ${paths.length} contract paths`);
