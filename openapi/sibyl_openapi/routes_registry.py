def _catalog_ops(
    path: str, name: str, plural: str, param: str, extra_rule: tuple[str, ...] = ()
) -> tuple[Op, ...]:
    base = f"/{path}"
    item = f"{base}/{{{param}}}"
    return (
        Op(
            "get",
            base,
            f"list{plural}",
            "registry",
            f"List {plural}",
            scope="agents:read",
            paged=True,
            query=(SEARCH_Q,),
            ok=((200, name, f"Page of {plural}"),),
        ),
        Op(
            "post",
            base,
            f"create{name}",
            "registry",
            f"Create a {name}",
            scope="agents:write",
            rules=(*extra_rule, TENANT_WIDE),
            idem=True,
            audit=("config.changed",),
            body=f"{name}Create",
            ok=((201, name, "Created"),),
            problems={409: ("slug_exists",)},
        ),
        Op(
            "get",
            item,
            f"get{name}",
            "registry",
            f"One {name}",
            scope="agents:read",
            ok=((200, name, name),),
            etag_out=True,
        ),
        Op(
            "patch",
            item,
            f"update{name}",
            "registry",
            f"Change a {name}",
            scope="agents:write",
            rules=(*extra_rule, TENANT_WIDE),
            if_match="required",
            audit=("config.changed",),
            body=f"{name}Patch",
            ok=((200, name, "Updated"),),
            etag_out=True,
        ),
    )


